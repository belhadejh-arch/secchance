function normalizeWilaya(value: string) {
  return value
    .replace(/^\s*\d{1,2}\s*[-.]\s*/, '')
    .split(/\s*[–—]\s*/)[0]
    .trim();
}

export function getNeighboringWilayas(wilayaName: string) {
  const normalized = normalizeWilaya(wilayaName);
  return neighborsByWilaya[normalized] ?? [];
}

export function getWilayaName(wilayaName: string) {
  return normalizeWilaya(wilayaName);
}
